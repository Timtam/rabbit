/// The file name `package_id` should install under, honoring a chosen
/// variant. `chosen` maps package id → variant id (what the user picked in
/// the wizard, or via the CLI). Falls back to the variant marked `default`,
/// then to the package's plain `install_as`, then to `None` (keep the
/// upstream name). An unknown variant id falls back the same way rather
/// than failing — the choice is a preference, not a correctness input.
pub fn resolved_install_as(spec: &PackageSpec, chosen: Option<&str>) -> Option<String> {
    if !spec.variants.is_empty() {
        if let Some(variant) = chosen.and_then(|id| spec.variants.iter().find(|v| v.id == id)) {
            return Some(variant.install_as.clone());
        }
        if let Some(default) = spec.variants.iter().find(|v| v.default) {
            return Some(default.install_as.clone());
        }
    }
    spec.install_as.clone()
}

/// The variant a receipt entry of `spec` describes, by the variant id the
/// entry recorded: that variant, or the default one when it recorded none
/// or one the manifest no longer has, as [`resolved_install_as`] falls
/// back. An install records no id when the user chose none, so the default
/// is the variant it installed. `None` for a package without variants.
pub fn recorded_variant<'a>(
    spec: &'a PackageSpec,
    recorded: Option<&str>,
) -> Option<&'a PackageVariant> {
    recorded
        .and_then(|id| spec.variants.iter().find(|variant| variant.id == id))
        .or_else(|| spec.variants.iter().find(|variant| variant.default))
}

/// The id of the variant `package_id`'s receipt entry describes, among
/// `specs`, by the variant id it recorded (see [`recorded_variant`]).
/// `None` for a package `specs` don't list or that has no variants.
pub fn recorded_variant_id(
    specs: &[PackageSpec],
    package_id: &str,
    recorded: Option<&str>,
) -> Option<String> {
    specs
        .iter()
        .find(|spec| spec.id == package_id)
        .and_then(|spec| recorded_variant(spec, recorded))
        .map(|variant| variant.id.clone())
}

/// The variant id that should be used for `package_id`: the user's explicit
/// choice for this run, else the one their last install recorded, else the
/// manifest default. Remembering matters because both Spanish variants come
/// from the same download — without it, an update would silently reinstall
/// a Team PMA user under the default `es_ES` name and switch their OSARA
/// translation back.
pub fn effective_variant_id(
    resource_path: &std::path::Path,
    package_id: &str,
    chosen: &std::collections::BTreeMap<String, String>,
) -> Option<String> {
    if let Some(explicit) = chosen.get(package_id) {
        return Some(explicit.clone());
    }
    crate::receipt::load_install_state(resource_path)
        .ok()
        .flatten()
        .and_then(|state| {
            state
                .packages
                .get(package_id)
                .and_then(|r| r.variant.clone())
        })
}

/// Package ids that share `package_id`'s exclusive group, excluding itself.
/// Empty when the package declares no group. Installing one member must
/// remove the others (REAPER loads exactly one language pack, so switching
/// German → Spanish, or between the two Spanish OSARA variants, must not
/// leave the previous file behind).
pub fn exclusive_group_siblings(package_id: &str) -> Vec<String> {
    let packages = embedded_package_manifest().packages;
    let Some(group) = packages
        .iter()
        .find(|spec| spec.id == package_id)
        .and_then(|spec| spec.exclusive_group.clone())
    else {
        return Vec::new();
    };
    packages
        .into_iter()
        .filter(|spec| spec.id != package_id && spec.exclusive_group.as_deref() == Some(&group))
        .map(|spec| spec.id)
        .collect()
}

/// How `package_id`'s versions are compared, per the embedded manifest.
/// Unknown packages fall back to the default ordered comparison.
pub fn version_comparison_for(package_id: &str) -> VersionComparison {
    version_comparison_on(package_id, None)
}

/// How `package_id`'s versions are compared on `channel`. REAPER's
/// development channel compares exactly: its builds carry a month and day
/// but no year, and release candidates sort after the final release under
/// the ordered comparison, so "different" is the only safe signal there.
pub fn version_comparison_on(package_id: &str, channel: Option<&str>) -> VersionComparison {
    embedded_package_manifest()
        .packages
        .into_iter()
        .find(|spec| spec.id == package_id)
        .map(|spec| spec.on_channel(channel).version_comparison)
        .unwrap_or_default()
}

/// The channel the last RABBIT install of `package_id` recorded at
/// `resource_path`, if it was anything other than stable and the manifest
/// still offers it. `None` means stable.
pub fn remembered_channel(resource_path: &std::path::Path, package_id: &str) -> Option<String> {
    let channel = crate::receipt::load_install_state(resource_path)
        .ok()
        .flatten()
        .and_then(|state| {
            state
                .packages
                .get(package_id)
                .and_then(|r| r.channel.clone())
        })?;
    let offered = embedded_package_manifest()
        .packages
        .iter()
        .any(|spec| spec.id == package_id && spec.offers_channel(&channel));
    offered.then_some(channel)
}

/// Every package among `package_ids` whose last install at `resource_path`
/// was on a non-stable channel the manifest still offers, mapped to that
/// channel. Used where the channel should persist between runs - the CLI,
/// and the wizard in expert mode. Outside expert mode the wizard passes an
/// empty map instead, which is what sends those packages back to stable.
pub fn remembered_channels(
    resource_path: &std::path::Path,
    package_ids: &[String],
) -> PackageChannels {
    package_ids
        .iter()
        .filter_map(|id| remembered_channel(resource_path, id).map(|channel| (id.clone(), channel)))
        .collect()
}

/// Whether `installed` should be replaced by `available` for a package using
/// `comparison`. Ordered packages update only on a strictly newer version;
/// exact (content-hash) packages update whenever the value differs at all,
/// since their "version" is a digest with no meaningful ordering.
pub fn version_needs_update(
    installed: &crate::version::Version,
    available: &crate::version::Version,
    comparison: VersionComparison,
) -> bool {
    match comparison {
        VersionComparison::Ordered => installed.cmp_lenient(available).is_lt(),
        VersionComparison::Exact => installed != available,
    }
}

/// The package ids `package_id` declares as dependencies in the embedded
/// manifest (empty if the package is unknown or standalone). The operation
/// pipeline uses this to cascade a failed dependency into a skip of its
/// dependents. Platform-independent: `depends_on` is a manifest-level field
/// that doesn't vary per platform.
pub fn package_dependencies(package_id: &str) -> Vec<String> {
    embedded_package_manifest()
        .packages
        .into_iter()
        .find(|spec| spec.id == package_id)
        .map(|spec| spec.depends_on)
        .unwrap_or_default()
}


/// Host-side facts the wizard / CLI consult to gate or escalate optional
/// packages. Lives in `rabbit-core` so callers (CLI, GUI) can share one
/// detection path. Probed via [`detect_host_capabilities`].
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct HostCapabilities {
    /// JAWS-for-Windows is installed for the current user. Gates the
    /// "JAWS-for-REAPER scripts" package's *visibility* via
    /// [`host_supports_package`].
    pub jaws_installed: bool,
    /// Native Instruments Komplete Kontrol is installed. Promotes
    /// ReaKontrol from `recommended: false` to recommended-by-default via
    /// [`effective_recommended`] without changing visibility.
    pub komplete_kontrol_installed: bool,
}

impl HostCapabilities {
    /// `true` iff `capability` is present on this host.
    pub fn has(&self, capability: HostCapability) -> bool {
        match capability {
            HostCapability::JawsInstalled => self.jaws_installed,
            HostCapability::KompleteKontrolInstalled => self.komplete_kontrol_installed,
        }
    }
}

/// Named host facilities a manifest entry can reference. Today this enum
/// drives [`PackageSpec::recommended_when`], but its design (one variant per
/// `HostCapabilities` field) is shared so future manifest fields can opt
/// into the same vocabulary.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum HostCapability {
    JawsInstalled,
    KompleteKontrolInstalled,
}

/// Snapshot the runtime host facts that gate or escalate optional packages.
pub fn detect_host_capabilities() -> HostCapabilities {
    HostCapabilities {
        jaws_installed: rabbit_platform::is_jaws_installed(),
        komplete_kontrol_installed: rabbit_platform::is_komplete_kontrol_installed(),
    }
}

/// `true` when the host can meaningfully receive `spec`. Returns `false` for
/// packages whose `package_kind` requires a host facility that isn't present
/// — today only [`PackageKind::ScreenReaderScripts`] needs this filter, and
/// it's a JAWS-presence check.
pub fn host_supports_package(spec: &PackageSpec, host: &HostCapabilities) -> bool {
    match spec.package_kind {
        PackageKind::ScreenReaderScripts => host.jaws_installed,
        PackageKind::ReaperApp
        | PackageKind::UserPluginBinary
        | PackageKind::Keymap
        | PackageKind::LanguagePack
        | PackageKind::ReapackPackage => true,
    }
}

/// Effective recommended state for `spec`, given the current host. Equals
/// `spec.recommended` unless `spec.recommended_when` names a present
/// capability, in which case it escalates to `true`. Use this everywhere
/// a "should this auto-tick / be in the default desired set?" decision is
/// made, not the raw [`PackageSpec::recommended`] field.
pub fn effective_recommended(spec: &PackageSpec, host: &HostCapabilities) -> bool {
    spec.recommended || spec.recommended_when.is_some_and(|cap| host.has(cap))
}

/// Whether `spec` is a language pack for the language RABBIT itself is
/// running in — the pack the wizard suggests (and ticks) by default.
///
/// Compares language subtags, so a pack declaring `es` matches an `es-ES`
/// *or* `es-MX` UI. English is deliberately never a match: REAPER is already
/// English, so no pack exists (or is wanted) for it.
pub fn matches_ui_language(spec: &PackageSpec, locale: &str) -> bool {
    let Some(language) = spec.language.as_deref() else {
        return false;
    };
    if language.eq_ignore_ascii_case("en") {
        return false;
    }
    let ui_language = locale.split(['-', '_']).next().unwrap_or(locale);
    ui_language.eq_ignore_ascii_case(language)
}

/// Build the package manifest by parsing every embedded per-package file
/// (gathered by build.rs) into an [`EmbeddedPackageSpec`]. Files are already
/// sorted by name (numeric-prefix order); the result keeps that order so the
/// wizard's package list is stable.
pub fn embedded_package_manifest() -> PackageManifest {
    let packages = EMBEDDED_PACKAGE_SOURCES
        .iter()
        .map(|(name, source)| {
            let spec = parse_embedded_package_spec(source)
                .unwrap_or_else(|err| panic!("embedded package file {name} should parse: {err}"));
            if let Err(message) = validate_package_spec(&spec) {
                panic!("embedded package file {name} is invalid: {message}");
            }
            spec
        })
        .collect();
    PackageManifest {
        schema_version: PACKAGE_MANIFEST_SCHEMA_VERSION,
        packages,
    }
}

/// Validate a parsed package spec's artifact configuration. The embedded
/// manifest is first-party data gathered at compile time, so a violation is a
/// developer error surfaced as a panic at startup/test time (alongside the
/// parse panic above) rather than a download-time failure.
///
/// Rules: a package declares its download via at most ONE of `github_release`
/// / `http_artifact` / `hfs_listing`; and every `github_release` asset must
/// resolve an artifact kind from its own `artifact_kind` or the spec-wide
/// fallback (so the resolver never has to guess a kind). The uninstall block
/// has rules of its own, in [`uninstall`].
pub fn validate_package_spec(spec: &EmbeddedPackageSpec) -> Result<(), String> {
    validate_resolvable_spec(spec)?;
    // Channels change where a build comes from, never how it comes off, so
    // the uninstall block is checked once, on the package itself.
    uninstall::validate_uninstall_spec(spec)?;
    validate_leave_to_reapack(spec)?;
    validate_former_install_destinations(spec)?;
    validate_plugin_bundle(spec)?;
    // Pull-request builds need a pull request number, which only a channel
    // parameter supplies. On the package itself it could never resolve.
    if spec.github_actions_artifact.is_some() {
        return Err(
            "github_actions_artifact is only allowed on a channel that takes a pull request"
                .to_string(),
        );
    }

    let mut seen = std::collections::BTreeSet::new();
    for channel in &spec.channels {
        if channel.id.contains(':') {
            return Err(format!(
                "channel id {:?} may not contain ':', which separates a channel from its parameter",
                channel.id
            ));
        }
        if channel.id.is_empty() || channel.id == STABLE_CHANNEL {
            return Err(format!(
                "channel id {:?} is reserved or empty; the package itself is the stable channel",
                channel.id
            ));
        }
        if !seen.insert(channel.id.as_str()) {
            return Err(format!("declares channel {:?} twice", channel.id));
        }
        // A pull request number is only any use to a source that looks one
        // up, and that source can't resolve without one.
        match (channel.parameter, channel.github_actions_artifact.is_some()) {
            (Some(ChannelParameter::PullRequest), false) => {
                return Err(format!(
                    "channel {:?} takes a pull request but has no github_actions_artifact to look it up",
                    channel.id
                ));
            }
            (None, true) => {
                return Err(format!(
                    "channel {:?} uses github_actions_artifact, which needs `parameter: pull_request`",
                    channel.id
                ));
            }
            _ => {}
        }
        // A channel must resolve on its own, exactly as the package does:
        // at most one artifact source, a valid What's-New pattern, and so on.
        validate_resolvable_spec(&spec.overlaid_with(channel, None))
            .map_err(|message| format!("channel {:?}: {message}", channel.id))?;
    }
    Ok(())
}

/// A package left to ReaPack must be able to tell when ReaPack installed it:
/// its version comes from ReaPack's records, its uninstall refuses a copy
/// ReaPack still manages, it installs where ReaPack can, inside the
/// resource folder, and its plug-in names on each of its platforms find its
/// file in ReaPack's records. Without those names the flag would never
/// apply. ReaPack lists itself in its records, so on ReaPack the flag would
/// stop RABBIT from ever updating it.
fn validate_leave_to_reapack(spec: &EmbeddedPackageSpec) -> Result<(), String> {
    if !spec.leave_to_reapack {
        return Ok(());
    }
    if spec.id == PACKAGE_REAPACK {
        return Err("leave_to_reapack can't be set on ReaPack itself".to_string());
    }
    if spec.user_plugin_prefixes.is_empty()
        || spec
            .user_plugin_prefixes
            .iter()
            .any(|prefix| prefix.is_empty())
    {
        return Err("leave_to_reapack needs user_plugin_prefixes, none of them empty".to_string());
    }
    if let Some(platform) = spec.supported_platforms.iter().find(|platform| {
        spec.user_plugin_suffixes
            .for_platform(platform.platform())
            .is_empty()
    }) {
        return Err(format!(
            "leave_to_reapack needs user_plugin_suffixes for {platform:?}"
        ));
    }
    if !spec.detectors.contains(&PackageDetector::ReapackRegistry) {
        return Err("leave_to_reapack needs the reapack_registry detector".to_string());
    }
    if spec.uninstall.reapack_owned != uninstall::ReapackOwnedPolicy::Block {
        return Err("leave_to_reapack needs uninstall.reapack_owned: block".to_string());
    }
    if spec.install_destination.resource_components().is_none() {
        return Err(
            "leave_to_reapack needs an install folder inside the resource folder".to_string(),
        );
    }
    Ok(())
}

/// A plug-in bundle comes from an archive and installs by the bundle step
/// alone, into a folder inside the resource folder, where its receipt
/// records each file by its path below the resource folder. Its detector
/// finds it, its names are plain names Windows opens as written, and
/// nothing renames it. The bundle step and detector need a bundle to
/// install and find.
fn validate_plugin_bundle(spec: &EmbeddedPackageSpec) -> Result<(), String> {
    let step = spec.install_steps.contains(&InstallStep::CopyPluginBundle);
    let detector = spec.detectors.contains(&PackageDetector::PluginBundle);
    let Some(bundle) = &spec.plugin_bundle else {
        if step || detector {
            return Err(
                "the copy_plugin_bundle step and the plugin_bundle detector need a plugin_bundle"
                    .to_string(),
            );
        }
        return Ok(());
    };
    if spec.install_steps != [InstallStep::CopyPluginBundle] {
        return Err("plugin_bundle needs install_steps [\"copy_plugin_bundle\"] alone".to_string());
    }
    if !detector {
        return Err("plugin_bundle needs the plugin_bundle detector".to_string());
    }
    if spec.install_destination.resource_components().is_none() {
        return Err("plugin_bundle needs an install folder inside the resource folder".to_string());
    }
    if !spec.former_install_destinations.is_empty() {
        return Err("plugin_bundle can't have former_install_destinations".to_string());
    }
    if spec.install_as.is_some() || !spec.variants.is_empty() {
        return Err("plugin_bundle can't be renamed by install_as or variants".to_string());
    }
    if !uninstall::is_plain_file_name(&bundle.name) {
        return Err(format!(
            "plugin_bundle name {:?} must be one plain file name",
            bundle.name
        ));
    }
    if !bundle
        .binary_components()
        .all(uninstall::is_plain_file_name)
    {
        return Err(format!(
            "plugin_bundle binary {:?} must be plain names separated by /",
            bundle.binary
        ));
    }
    let archive = Some(GithubArtifactKind::Archive);
    let all_archives = spec.github_release.as_ref().is_none_or(|release| {
        release
            .assets
            .iter()
            .all(|selector| selector.artifact_kind.or(release.artifact_kind) == archive)
    }) && spec.http_artifact.as_ref().is_none_or(|http| {
        http.targets
            .iter()
            .all(|target| Some(target.artifact_kind) == archive)
    }) && spec
        .hfs_listing
        .as_ref()
        .is_none_or(|hfs| Some(hfs.artifact_kind) == archive);
    if !all_archives {
        return Err("plugin_bundle needs every download to be an archive".to_string());
    }
    // A channel brings a download of its own, which would need the same
    // check; no bundle package has one.
    if !spec.channels.is_empty() {
        return Err("plugin_bundle can't have channels".to_string());
    }
    validate_plugin_bundle_uninstall(spec, bundle)
}

/// A plug-in bundle comes off by its receipt alone: without one, RABBIT
/// can't tell its files from what else sits in the bundle, so the package
/// needs `requires_receipt`. Each `remove_files` plan takes the receipt's
/// files and then the bundle's folder with every folder in it, once empty,
/// by the path the install puts it at, so the two can't drift apart.
fn validate_plugin_bundle_uninstall(
    spec: &EmbeddedPackageSpec,
    bundle: &PluginBundleSpec,
) -> Result<(), String> {
    if !spec.uninstall.requires_receipt {
        return Err("plugin_bundle needs uninstall.requires_receipt".to_string());
    }
    // Checked to be inside the resource folder above.
    let components = spec
        .install_destination
        .resource_components()
        .unwrap_or_default();
    let tree = std::iter::once("{resource}")
        .chain(components.iter().copied())
        .chain(std::iter::once(bundle.name.as_str()))
        .collect::<Vec<_>>()
        .join("/");
    for plan in &spec.uninstall.plans {
        if plan.strategy != uninstall::UninstallStrategy::RemoveFiles {
            continue;
        }
        if !plan.remove.receipt_files {
            return Err("plugin_bundle needs receipt_files in its remove_files plans".to_string());
        }
        if !plan
            .remove
            .trees_if_empty
            .iter()
            .any(|path| path.as_str() == tree)
        {
            return Err(format!(
                "plugin_bundle needs {tree} in the trees_if_empty of its remove_files plans"
            ));
        }
    }
    Ok(())
}

/// A former install folder is one the package no longer installs into,
/// named once.
fn validate_former_install_destinations(spec: &EmbeddedPackageSpec) -> Result<(), String> {
    for (index, destination) in spec.former_install_destinations.iter().enumerate() {
        if *destination == spec.install_destination {
            return Err(format!(
                "former_install_destinations names {destination:?}, where the package installs now"
            ));
        }
        if spec.former_install_destinations[..index].contains(destination) {
            return Err(format!(
                "former_install_destinations names {destination:?} twice"
            ));
        }
    }
    Ok(())
}

/// The checks that apply to anything the resolvers will be handed: the
/// package as declared, and the package on each of its channels.
fn validate_resolvable_spec(spec: &EmbeddedPackageSpec) -> Result<(), String> {
    let sources = [
        ("github_release", spec.github_release.is_some()),
        ("http_artifact", spec.http_artifact.is_some()),
        ("hfs_listing", spec.hfs_listing.is_some()),
        (
            "github_actions_artifact",
            spec.github_actions_artifact.is_some(),
        ),
    ];
    let set: Vec<&str> = sources
        .iter()
        .filter(|(_, present)| *present)
        .map(|(name, _)| *name)
        .collect();
    if set.len() > 1 {
        return Err(format!(
            "sets multiple artifact sources ({}); a package must declare exactly one",
            set.join(", ")
        ));
    }

    if let Some(github_release) = &spec.github_release {
        for (index, selector) in github_release.assets.iter().enumerate() {
            if selector
                .artifact_kind
                .or(github_release.artifact_kind)
                .is_none()
            {
                return Err(format!(
                    "github_release asset #{index} has no artifact_kind and the spec sets no fallback artifact_kind"
                ));
            }
        }
    }

    // A broken `whats_new` regex would otherwise only surface at fetch time,
    // where notes failures are deliberately silent — so a first-party typo
    // would quietly disable the What's-New pane instead of failing loudly.
    if let Some(WhatsNewRule::TextChangelog { section_start, .. }) = &spec.whats_new
        && let Err(err) = regex::Regex::new(section_start)
    {
        return Err(format!(
            "whats_new section_start regex {section_start:?} is invalid: {err}"
        ));
    }

    Ok(())
}

/// Total size in bytes of the embedded per-package manifest files. Reported
/// by the portability self-check as a rough "the embedded manifest is intact"
/// signal.
pub fn embedded_package_manifest_bytes() -> usize {
    EMBEDDED_PACKAGE_SOURCES
        .iter()
        .map(|(_, source)| source.len())
        .sum()
}


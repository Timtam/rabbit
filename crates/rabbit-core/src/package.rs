/// How a package's installed version is compared against the available one
/// to decide Install / Update / Keep.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum VersionComparison {
    /// Newer-than comparison over numeric segments ([`Version::cmp_lenient`]).
    /// The default, and correct for every package with a real version string.
    #[default]
    Ordered,
    /// Equality: anything other than an exact match means "update". Required
    /// for [`VersionRule::ContentHash`] packages, whose "version" is a hex
    /// digest that has no meaningful ordering.
    Exact,
}

fn default_capture_format() -> String {
    "{1}".to_string()
}

/// Data-driven What's-New (release notes) discovery for the wizard's
/// package-details pane. Like [`VersionRule`], each variant fetches a URL and
/// extracts human-readable notes, so a package's notes side is manifest data
/// rather than a per-package Rust parser. Notes are best-effort: a fetch or
/// parse failure leaves the pane without a What's-New section instead of
/// failing the version check.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum WhatsNewRule {
    /// Fetch `url` (JSON) and read the commit list at `pointer` (an RFC 6901
    /// JSON pointer): an array of `[sha, message]` pairs, newest first.
    /// Rendered as one bulleted line per commit, keeping only each message's
    /// first line (full bodies can run to paragraphs). When the installed
    /// version embeds the built commit's hash after a comma (OSARA's
    /// snapshot convention), the list is trimmed to the commits above that
    /// hash. Covers OSARA's `update.json` `commits` field — the same feed
    /// OSARA's own updater shows as its list of changes.
    JsonCommits { url: String, pointer: String },
    /// Fetch the head of `url` — a plain-text changelog with the newest
    /// release first — and cut the newest run of sections. Sections start at
    /// lines matching the `section_start` regex (compiled in multi-line
    /// mode); the run reaches from the first match down to, excluding, the
    /// installed version's section, or is the first section alone when no
    /// installed version is known. Covers REAPER's `whatsnew.txt`
    /// (`v7.78 - July 18 2026` section headers) and SWS's
    /// (`!v2.14.0.7 featured build …` headers).
    TextChangelog { url: String, section_start: String },
    /// Fetch `url` — a GitHub `/releases` list endpoint (or a single
    /// `/releases/latest` object) — and render each release's name plus its
    /// `body`, the notes the maintainer wrote, walking back to the installed
    /// version's release when one is known. Covers ReaPack. Only declare
    /// this for packages whose releases carry real notes: rolling snapshot
    /// tags (ReaKontrol, Surge XT, app2clap) have a static boilerplate body
    /// that would be worse than showing nothing.
    GithubReleaseBody { url: String },
}

/// A detection probe. Listed in `detectors` per package and run by the
/// detection engine in order, so the manifest declares both *which* probes
/// apply and their fallback order. `RabbitReceipt` (authoritative) and
/// `UserPluginFile` (file presence) are special bookends; the rest are
/// version probes / out-of-tree detectors, some carrying their parameters
/// as data (registry name, scan pattern), some selecting a bespoke engine
/// helper whose domain logic is irreducible.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PackageDetector {
    /// RABBIT's own install receipt — authoritative version, checked first.
    RabbitReceipt,
    /// A matching file's presence in the package's install destination.
    UserPluginFile,
    /// The detected file's PE / Mach-O version metadata.
    FileVersionMetadata,
    /// The ReaPack local registry's recorded version for the file.
    ReapackRegistry,
    /// The Windows uninstall-registry `DisplayVersion` for `display_name`
    /// (e.g. OSARA's installer entry, shown in Programs and Features).
    UninstallDisplayVersion { display_name: String },
    /// A best-effort scan of the detected binary for a version string matched
    /// by `pattern` (regex, capture group 1), reported as `label` with
    /// `note`. Generalizes the OSARA / ReaKontrol / SWS / ReaPack embedded-
    /// version-string scanners (each just a different anchored pattern).
    BinaryVersionString {
        pattern: String,
        label: String,
        note: String,
    },
    /// FFmpeg's bespoke 3-probe detector (`ffmpeg.exe` StringFileInfo →
    /// binary banner scan → `avformat-XX` filename → libavformat-major map).
    /// The map (`lib_major - 54`) and probe orchestration stay in the engine.
    FfmpegLibavformat,
    /// JAWS-for-REAPER scripts: follow the Programs-and-Features uninstall
    /// key to the vendor `Uninstall.exe` and read its FileVersion resource.
    JawsUninstallExe,
    /// Surge XT: the Inno Setup uninstall `DisplayVersion` plus the system
    /// VST3 bundle's file metadata.
    SurgeVendorFiles,
    /// REAPER itself: the `reaper.exe` / `REAPER.app` the resource path
    /// belongs to, and the version it reports. REAPER installs no file into
    /// `UserPlugins`, so without this it has no detector of its own and is
    /// only ever as visible as its receipt.
    ReaperApp,
    /// The package's [`PluginBundleSpec`] folder in its install folder,
    /// with the binary inside it: a real folder and a real file, never a
    /// symbolic link or junction anywhere on the way. A bookend like
    /// `UserPluginFile`: it gives the binary to the version probes after it,
    /// such as `file_version_metadata`.
    PluginBundle,
}


/// Data-driven definition of a package distributed through GitHub releases,
/// read by BOTH the version side ([`crate::latest`]) and the download side
/// ([`crate::artifact`]). When a package carries one of these, adding or
/// maintaining it needs only this manifest block — no per-package Rust. It
/// is the generalization of the hand-written ReaKontrol/app2clap snapshot
/// parsers + resolvers into one parameterized engine.
///
/// A package sets exactly one artifact source — `github_release`,
/// `http_artifact`, or `hfs_listing` — enforced by [`validate_package_spec`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GithubReleaseSpec {
    /// `owner/name`, e.g. `jcsteh/app2clap`.
    pub repo: String,
    /// Which release to read: `/releases/latest` or `/releases/tags/<tag>`.
    pub release: GithubReleaseSelector,
    /// How to derive the version (from the tag, or from an asset filename).
    pub version_from: VersionSource,
    /// Per-platform (optionally per-arch) asset matchers used to pick the
    /// download. The version side ignores this — it reads `version_from`.
    pub assets: Vec<AssetSelector>,
    /// Spec-wide fallback for how the downloaded asset is handled. Optional:
    /// a package whose platforms need *different* kinds (Surge XT —
    /// `Installer` on Windows, `DiskImage` on macOS) leaves this `None` and
    /// sets [`AssetSelector::artifact_kind`] per asset instead. The resolved
    /// kind is `selector.artifact_kind.or(spec.artifact_kind)`; the load-time
    /// validator rejects a spec where neither is set for some asset.
    #[serde(default)]
    pub artifact_kind: Option<GithubArtifactKind>,
}

/// Which GitHub release a [`GithubReleaseSpec`] reads. Serializes as the
/// bare string `"latest"` or as `{ "tag": "<name>" }`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum GithubReleaseSelector {
    /// `GET /repos/<repo>/releases/latest`.
    Latest,
    /// `GET /repos/<repo>/releases/tags/<tag>` — a fixed or rolling tag
    /// (e.g. `snapshots`). Assets are sorted by version; release date/order
    /// is never trusted.
    Tag(String),
}

/// How a [`GithubReleaseSpec`] derives the package version. Serializes as
/// `{ "tag_name": { … } }` or `{ "asset_name": { … } }`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum VersionSource {
    /// The release's `tag_name`, optionally with a leading `v` stripped
    /// (ReaPack's `v1.2.6` → `1.2.6`).
    TagName {
        #[serde(default)]
        strip_v_prefix: bool,
    },
    /// The version embedded in the highest-sorting asset filename. The
    /// prefix/suffix to strip come from the matching [`AssetSelector`] (so a
    /// multi-platform package like ReaKontrol, whose Windows and macOS
    /// assets carry different prefixes, needs no per-platform version rule);
    /// `strip_trailing_dot_segment` additionally drops a trailing
    /// `.<segment>` (the short commit hash in
    /// `app2clap_2026.5.17.34.b6f558cf.zip`).
    AssetName {
        #[serde(default)]
        strip_trailing_dot_segment: bool,
    },
}

/// A per-platform (and optionally per-arch) rule for selecting the release
/// asset to download. Exactly one of (`name_prefix` + `name_suffix`) or
/// `exact_name` must be set — enforced at manifest load.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AssetSelector {
    pub platform: SupportedPlatform,
    /// `None` matches any host arch and the resolved descriptor reports
    /// `Architecture::Universal`; `Some` pins both the match and the
    /// reported architecture (ReaPack's per-slice DLLs).
    #[serde(default)]
    pub arch: Option<Architecture>,
    #[serde(default)]
    pub name_prefix: Option<String>,
    #[serde(default)]
    pub name_suffix: Option<String>,
    #[serde(default)]
    pub exact_name: Option<String>,
    /// Per-asset override of [`GithubReleaseSpec::artifact_kind`]. Lets a
    /// multi-platform package ship different kinds per slice (Surge XT's
    /// Windows `Installer` vs macOS `DiskImage`). `None` falls back to the
    /// spec-wide kind.
    #[serde(default)]
    pub artifact_kind: Option<GithubArtifactKind>,
    /// Compare the name, prefix and suffix ignoring ASCII upper and lower
    /// case, for a project that names its assets by hand and spells the
    /// same part both ways, such as LB-303's `.VST3.zip` beside the other
    /// instruments' `.vst3.zip`.
    #[serde(default, skip_serializing_if = "std::ops::Not::not")]
    pub ignore_case: bool,
}

impl AssetSelector {
    /// Whether `asset_name` satisfies this selector.
    pub fn matches_asset(&self, asset_name: &str) -> bool {
        if let Some(exact) = &self.exact_name {
            return if self.ignore_case {
                asset_name.eq_ignore_ascii_case(exact)
            } else {
                asset_name == exact
            };
        }
        let prefix_ok = self
            .name_prefix
            .as_deref()
            .is_none_or(|prefix| self.starts_with(asset_name, prefix));
        let suffix_ok = self
            .name_suffix
            .as_deref()
            .is_none_or(|suffix| self.ends_with(asset_name, suffix));
        prefix_ok && suffix_ok
    }

    /// The part of `asset_name` between the selector's prefix and suffix,
    /// when the name starts with the one and ends with the other, compared
    /// as [`Self::ignore_case`] says, and the two don't overlap. A missing
    /// prefix or suffix counts as empty.
    pub fn name_core<'a>(&self, asset_name: &'a str) -> Option<&'a str> {
        let prefix = self.name_prefix.as_deref().unwrap_or("");
        let suffix = self.name_suffix.as_deref().unwrap_or("");
        if !self.starts_with(asset_name, prefix) || !self.ends_with(asset_name, suffix) {
            return None;
        }
        asset_name.get(prefix.len()..asset_name.len() - suffix.len())
    }

    fn starts_with(&self, name: &str, prefix: &str) -> bool {
        name.get(..prefix.len())
            .is_some_and(|head| self.same(head, prefix))
    }

    fn ends_with(&self, name: &str, suffix: &str) -> bool {
        name.len()
            .checked_sub(suffix.len())
            .and_then(|start| name.get(start..))
            .is_some_and(|tail| self.same(tail, suffix))
    }

    /// Whether `found` is `wanted`, ignoring ASCII case when the selector
    /// says so.
    fn same(&self, found: &str, wanted: &str) -> bool {
        if self.ignore_case {
            found.eq_ignore_ascii_case(wanted)
        } else {
            found == wanted
        }
    }
}

/// How a downloaded artifact (a GitHub asset OR a scraped/fixed download) is
/// handled. Maps 1:1 onto [`crate::artifact::ArtifactKind`]. Shared by both
/// the [`GithubReleaseSpec`] path and the non-GitHub [`HttpArtifactSpec`] path.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum GithubArtifactKind {
    /// A `.zip` from which the matching plugin file is extracted.
    Archive,
    /// A bare plugin file dropped in place (ReaPack's `.dll`/`.dylib`).
    ExtensionBinary,
    /// A vendor `.exe`/`.pkg` installer run by `run_upstream_installer`
    /// (REAPER, SWS, OSARA-win, Surge XT-win).
    Installer,
    /// A macOS `.dmg` (REAPER, SWS-mac, Surge XT-mac).
    DiskImage,
    /// A `.7z` archive (FFmpeg shared builds). Extracted by the dedicated 7z
    /// path since the `zip` crate can't read it.
    SevenZipArchive,
}

/// Where a data-driven package installs its file.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
#[serde(rename_all = "snake_case")]
pub enum InstallDestination {
    /// `<resource>/UserPlugins/` — the default for REAPER extensions.
    #[default]
    UserPlugins,
    /// `<resource>/UserPlugins/FX/` — REAPER's own plug-in folder for this
    /// REAPER, scanned for VST, VST3 and CLAP. Inside the resource path, so
    /// it needs no administrator rights and works for portable installs
    /// too. Other plug-ins share it, so a file there is a package's only by
    /// its receipt or its plug-in names.
    UserPluginsFx,
    /// `%LOCALAPPDATA%\Programs\Common\CLAP` — the per-user CLAP folder,
    /// outside any REAPER resource path. No built-in package installs there
    /// any more: app2clap did until it moved to `UserPluginsFx`, and names
    /// it among its former destinations. It stays so that the folder keeps
    /// a name in the manifest, and RABBIT still backs up and restores files
    /// there (see `crate::install::outside_install_roots`).
    WindowsClapDir,
    /// `<resource>/LangPack/` — where REAPER looks for `.ReaperLangPack`
    /// translation files. Inside the resource path, so it works for portable
    /// installs too.
    LangPack,
}

impl InstallDestination {
    /// The folder's path components below the resource folder, or `None`
    /// for a folder outside every resource folder.
    pub fn resource_components(self) -> Option<&'static [&'static str]> {
        match self {
            Self::UserPlugins => Some(&["UserPlugins"]),
            Self::UserPluginsFx => Some(&["UserPlugins", "FX"]),
            Self::LangPack => Some(&["LangPack"]),
            Self::WindowsClapDir => None,
        }
    }

    /// The folder inside the resource folder `resource`, joined one
    /// component at a time, so a receipt records the path below it with
    /// the platform's own separator. `None` for a folder outside every
    /// resource folder.
    pub fn folder_in(self, resource: &Path) -> Option<PathBuf> {
        self.resource_components().map(|components| {
            components
                .iter()
                .fold(resource.to_path_buf(), |folder, component| {
                    folder.join(component)
                })
        })
    }

    /// The folder outside every resource folder that this destination
    /// names on this computer: the CLAP folder, which resolves only on
    /// Windows. `None` for a folder inside the resource folder.
    pub fn outside_folder(self) -> Option<PathBuf> {
        match self {
            Self::WindowsClapDir => rabbit_platform::windows_clap_dir(),
            Self::UserPlugins | Self::UserPluginsFx | Self::LangPack => None,
        }
    }
}

/// A plug-in bundle a package installs as a whole: a folder such as
/// `LJuno-116.vst3` that holds the plug-in's binary and its resources at
/// fixed places below it, as VST3 plug-ins come. The release archive holds
/// the folder at its top. RABBIT installs every file in it into the
/// package's install folder at the same path below it, and ignores
/// everything else in the archive (see
/// [`crate::archive::extract_plugin_bundle_from_archive`]).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PluginBundleSpec {
    /// The bundle folder's name, in the archive and in the install folder,
    /// such as `LJuno-116.vst3`. A plain name, never a path.
    pub name: String,
    /// The plug-in's binary, by its path inside the bundle with `/` between
    /// the folders, such as `Contents/x86_64-win/LJuno-116.vst3`. An install
    /// puts it in place after every other file of the bundle, detection
    /// looks for it, and its version resource gives the version when no
    /// receipt does.
    pub binary: String,
}

impl PluginBundleSpec {
    /// The binary's path inside the bundle, one name per folder.
    pub fn binary_components(&self) -> impl Iterator<Item = &str> {
        self.binary.split('/')
    }

    /// The bundle folder inside `folder`, the package's install folder.
    pub fn folder_in(&self, folder: &Path) -> PathBuf {
        folder.join(&self.name)
    }

    /// The binary inside the bundle folder `bundle`, joined one name at a
    /// time, so the path has the platform's own separator.
    pub fn binary_in(&self, bundle: &Path) -> PathBuf {
        self.binary_components()
            .fold(bundle.to_path_buf(), |path, name| path.join(name))
    }

    /// Whether `path` is this bundle's binary in the install folder
    /// `folder`, by its names ignoring case, as an archive may spell the
    /// names below the bundle's folder in either case.
    pub fn is_binary_in(&self, folder: &Path, path: &Path) -> bool {
        crate::uninstall::paths::same_ignoring_case(&self.binary_in(&self.folder_in(folder)), path)
    }
}

/// The plug-in bundle of `package_id` by the embedded manifest, with the
/// folder it installs into, or `None` for a package without one. The
/// manifest is read once for this: install, restore and uninstall ask it
/// about single files.
pub(crate) fn plugin_bundle_of(
    package_id: &str,
) -> Option<(InstallDestination, &'static PluginBundleSpec)> {
    static BUNDLES: std::sync::OnceLock<BTreeMap<String, (InstallDestination, PluginBundleSpec)>> =
        std::sync::OnceLock::new();
    BUNDLES
        .get_or_init(|| {
            embedded_package_manifest()
                .packages
                .into_iter()
                .filter_map(|spec| {
                    let bundle = spec.plugin_bundle?;
                    Some((spec.id, (spec.install_destination, bundle)))
                })
                .collect()
        })
        .get(package_id)
        .map(|(destination, bundle)| (*destination, bundle))
}

/// Data-driven artifact (download) resolution for packages that are NOT a
/// single GitHub release: REAPER (reaper.fm scrape), OSARA (snapshot-index
/// scrape), SWS (home-page scrape) and FFmpeg (per-arch dual source). Read
/// only by [`crate::artifact`]; the version side keeps using [`VersionRule`]
/// and the resolved version is stamped onto the descriptor.
///
/// Every target is keyed by `(platform, match_arches)`. The first target
/// whose platform matches and whose `match_arches` contains the (already
/// canonicalized) dispatch arch wins. No matching target yields
/// `NoArtifactFound` — this is how SWS rejects Windows-on-ARM and FFmpeg
/// rejects x86/macOS, with no per-package Rust. A package sets EXACTLY ONE of
/// `github_release` / `http_artifact` / `hfs_listing` (enforced by the
/// load-time validator).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HttpArtifactSpec {
    pub targets: Vec<HttpArtifactTarget>,
}

/// One `(platform, arches)` → download rule.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HttpArtifactTarget {
    pub platform: SupportedPlatform,
    /// Input dispatch arches (post-`canonicalize_dispatch_arch`) this target
    /// serves. The arch-collapse fan-in lives here: REAPER-win lists
    /// `["x64","universal","unknown"]` on its x64 target. `universal`/`unknown`
    /// are accepted belt-and-suspenders even though canonicalization usually
    /// rewrites them to a concrete host slice first.
    pub match_arches: Vec<Architecture>,
    /// Architecture stamped on the resulting descriptor (REWRITES arch:
    /// win x64-target → `x64`, mac universal-target → `universal`, osara →
    /// `universal`, ffmpeg-arm64 → `arm64`). Independent of `match_arches`.
    pub report_arch: Architecture,
    pub artifact_kind: GithubArtifactKind,
    /// How the download URL + file name are produced.
    pub source: HttpArtifactSource,
}

/// The shapes the snowflakes need. Externally tagged (`serde` tag = variant).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum HttpArtifactSource {
    /// Scrape an HTML page for the FIRST `<a href>` whose value matches.
    /// Covers REAPER, OSARA, SWS. The matched href becomes the download URL
    /// via `absolute_url(base_url, href)`; the file name is its basename. The
    /// version comes from the package's [`VersionRule`] and is stored on the
    /// descriptor only (never interpolated).
    ScrapeHref {
        page_url: String,
        base_url: String,
        /// Anchored predicate over the href. `contains` is an AND-list;
        /// `not_contains` disambiguates REAPER's x86 `-install.exe` (a
        /// substring of the x64/arm64 hrefs) so matching is order-INDEPENDENT
        /// instead of relying on document order; `ends_with` pins the
        /// extension.
        #[serde(rename = "match")]
        href_match: HrefMatch,
    },
    /// A fixed download URL (no version interpolation). Covers FFmpeg x64
    /// (Gyan redirector). `file_name` overrides the URL basename so the cache
    /// layout stays stable if the redirector path changes.
    FixedUrl {
        url: String,
        #[serde(default)]
        file_name: Option<String>,
    },
    /// Highest *stable* GitHub release whose major == `supported_major`, then
    /// the asset matching `asset`. Covers FFmpeg arm64 (tordona). The version
    /// is the picked release's, NOT the package `VersionRule`. Distinct from
    /// `github_release` because tags are plain `MAJOR.MINOR.PATCH` and
    /// "newest within a pinned major" isn't expressible by
    /// [`GithubReleaseSelector`].
    GithubReleaseMaxMajor {
        /// `owner/name`, e.g. `tordona/ffmpeg-win-arm64`.
        repo: String,
        /// Major-version gate; must equal `FFMPEG_SUPPORTED_MAJOR`.
        supported_major: u64,
        asset: AssetMatch,
    },
}

/// Anchored href predicate for [`HttpArtifactSource::ScrapeHref`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HrefMatch {
    #[serde(default)]
    pub contains: Vec<String>,
    #[serde(default)]
    pub not_contains: Vec<String>,
    #[serde(default)]
    pub ends_with: Option<String>,
}

impl HrefMatch {
    /// Whether `href` satisfies every clause (all `contains`, no
    /// `not_contains`, optional `ends_with`).
    pub fn matches(&self, href: &str) -> bool {
        self.contains.iter().all(|needle| href.contains(needle))
            && self
                .not_contains
                .iter()
                .all(|needle| !href.contains(needle))
            && self.ends_with.as_ref().is_none_or(|s| href.ends_with(s))
    }
}

/// Asset predicate for [`HttpArtifactSource::GithubReleaseMaxMajor`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AssetMatch {
    #[serde(default)]
    pub contains: Vec<String>,
    #[serde(default)]
    pub ends_with: Option<String>,
}

impl AssetMatch {
    pub fn matches(&self, name: &str) -> bool {
        self.contains.iter().all(|needle| name.contains(needle))
            && self.ends_with.as_ref().is_none_or(|s| name.ends_with(s))
    }
}

/// Data-driven definition of a package distributed through a rejetto HFS
/// folder listing (`hoard.reaperaccessibility.com`). Like [`GithubReleaseSpec`]
/// it drives BOTH the version side ([`crate::latest`]) and the download side
/// ([`crate::artifact`]) from one source: the engine reads the folder listing,
/// picks the highest-version installer, and uses it for both. Covers JAWS-for-
/// REAPER scripts — the one package that isn't a web page or GitHub release.
/// The HFS `get_file_list` protocol and the `.exe` highest-version pick stay as
/// engine helpers selected by this block (the same "spec selects an irreducible
/// helper" pattern as [`HttpArtifactSource::GithubReleaseMaxMajor`]).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HfsListingSpec {
    /// rejetto HFS server root, e.g. `https://hoard.reaperaccessibility.com`.
    pub base: String,
    /// URL-encoded folder path under the root whose listing is read.
    pub folder: String,
    /// How the picked file is handled (JAWS ships an `Installer` `.exe`).
    pub artifact_kind: GithubArtifactKind,
}

/// Data-driven latest-version discovery for packages that don't come from a
/// GitHub release. Each variant fetches a URL and extracts a version, so a
/// snowflake's version side is manifest data rather than a per-package Rust
/// parser. Serializes as `{ "html": { … } }` / `{ "json": { … } }` /
/// `{ "plain_text": { … } }`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum VersionRule {
    /// Fetch `url`, match `pattern` (a regex) against the body, and build the
    /// version from the capture groups via `format` (default `"{1}"`, i.e.
    /// the first group). Covers HTML scrapes like REAPER's
    /// `Version ([0-9.]+)` and SWS's two-group `base` + `#build`
    /// (`format: "{1}.{2}"`).
    Html {
        url: String,
        pattern: String,
        #[serde(default = "default_capture_format")]
        format: String,
    },
    /// Fetch `url` (JSON) and read the string at `pointer` (an RFC 6901 JSON
    /// pointer, e.g. `/version`). Covers OSARA's `update.json`.
    Json { url: String, pointer: String },
    /// Fetch `url` and parse the trimmed body as a version. Covers FFmpeg's
    /// Gyan `*.ver` plain-text endpoint.
    PlainText { url: String },
    /// Fetch `url` and use the SHA-256 of the response body as the version.
    /// For artifacts published without any version string — community REAPER
    /// language packs are a fixed URL on a translator's web server, updated
    /// in place — the content digest IS the identity: a changed digest means
    /// a new release. Pair with [`VersionComparison::Exact`], since ordering
    /// two hex digests is meaningless.
    ContentHash { url: String },
}

/// One selectable flavour of a package that differs only in the file name
/// it installs under. REAPER picks a language pack by file name and OSARA
/// reads that name to choose its own translation, so Spanish has two: the
/// same REAPER/SWS translation is published as `es_ES` (which loads the
/// "REAPER Accesible español" OSARA translation) or `es_MX` (Team PMA's).
/// Same download either way — only the installed name differs.
/// A build published as a GitHub Actions workflow artifact - the test build
/// OSARA's CI makes for every pull request.
///
/// Found through GitHub's public REST API, which lists a repository's
/// artifacts without authentication, and downloaded through nightly.link,
/// because GitHub's own artifact download needs a signed-in user. That is the
/// same link OSARA's own pull-request bot posts for testers.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GithubActionsArtifactSpec {
    /// `owner/name`.
    pub repo: String,
    /// Download URL, with `{repo}` and `{id}` (the artifact id) filled in.
    pub download_url: String,
    pub targets: Vec<GithubActionsArtifactTarget>,
    /// The pull request whose build to install. Filled in from the channel's
    /// parameter (`pr:1454`) when the package is put on that channel; never
    /// read from the manifest.
    #[serde(skip)]
    pub pull_request: Option<u32>,
}

/// One platform's artifact within a [`GithubActionsArtifactSpec`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GithubActionsArtifactTarget {
    pub platform: SupportedPlatform,
    /// Artifact names are `<name_prefix><version>`, where the version names
    /// the pull request, the CI run and the commit: `pr1454-534,240c4663`.
    pub name_prefix: String,
    pub report_arch: Architecture,
    /// The kind of file inside the downloaded zip. An `installer` arrives
    /// zipped and is unwrapped before it runs.
    pub artifact_kind: GithubArtifactKind,
}

/// The channel every package is on unless something says otherwise: builds
/// exactly as the package's own manifest entry describes them.
pub const STABLE_CHANNEL: &str = "stable";

/// Which channel each package should use for one run, by package id. A
/// package that is absent, or mapped to [`STABLE_CHANNEL`], resolves exactly
/// as its manifest entry declares. Callers pass a fully decided map: the
/// install pipeline never guesses a channel on its own.
pub type PackageChannels = BTreeMap<String, String>;

/// An alternative place a package's builds come from - REAPER's development
/// builds on landoleet.org, say.
///
/// Not a [`PackageVariant`]. A variant is the *same* download installed under
/// a different file name, and never reaches artifact resolution; a channel
/// changes where the download comes from, how its version is read and
/// compared, and where its release notes live. Every field the channel sets
/// replaces the package's own while the package is on this channel; every
/// field it leaves out is inherited unchanged.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PackageChannel {
    /// Stable id used by `--package-channel` and recorded in the receipt.
    pub id: String,
    /// Fluent key for the channel's display name.
    pub display_name_key: String,
    /// Offered in the wizard only while expert mode is on. The CLI needs no
    /// unlock: it already counts as the expert interface.
    #[serde(default)]
    pub expert: bool,
    /// What, if anything, follows the id after a colon. OSARA's pull-request
    /// channel is `pr:1454`: one channel, parameterised by the pull request
    /// whose build to install. A channel without a parameter is written as
    /// its bare id.
    #[serde(default)]
    pub parameter: Option<ChannelParameter>,
    #[serde(default)]
    pub version: Option<VersionRule>,
    #[serde(default)]
    pub version_comparison: Option<VersionComparison>,
    #[serde(default)]
    pub whats_new: Option<WhatsNewRule>,
    /// An artifact source replaces the package's source outright rather than
    /// merging with it, because a package may only ever declare one.
    #[serde(default)]
    pub github_release: Option<GithubReleaseSpec>,
    #[serde(default)]
    pub http_artifact: Option<HttpArtifactSpec>,
    #[serde(default)]
    pub hfs_listing: Option<HfsListingSpec>,
    #[serde(default)]
    pub github_actions_artifact: Option<GithubActionsArtifactSpec>,
}

/// The kind of value a parameterised channel takes after its colon.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ChannelParameter {
    /// A pull request number, e.g. the `1454` in `pr:1454`.
    PullRequest,
}

impl ChannelParameter {
    fn accepts(self, value: &str) -> bool {
        match self {
            // Only the plain form, so `pr:01454` or `pr:+1454` can't become a
            // second name for `pr:1454` that a receipt then compares unequal.
            ChannelParameter::PullRequest => value
                .parse::<u32>()
                .is_ok_and(|number| number > 0 && number.to_string() == value),
        }
    }
}

/// Split a channel string into its id and optional parameter: `dev` gives
/// (`dev`, None), `pr:1454` gives (`pr`, Some(`1454`)).
pub fn split_channel(channel: &str) -> (&str, Option<&str>) {
    match channel.split_once(':') {
        Some((id, parameter)) => (id, Some(parameter)),
        None => (channel, None),
    }
}

impl PackageChannel {
    /// Whether `parameter` (the part after the colon, if any) is exactly what
    /// this channel expects: nothing for a plain channel, a well-formed value
    /// for a parameterised one.
    fn accepts_parameter(&self, parameter: Option<&str>) -> bool {
        match (self.parameter, parameter) {
            (None, None) => true,
            (Some(kind), Some(value)) => kind.accepts(value),
            _ => false,
        }
    }

    fn sets_artifact_source(&self) -> bool {
        self.github_release.is_some()
            || self.http_artifact.is_some()
            || self.hfs_listing.is_some()
            || self.github_actions_artifact.is_some()
    }
}

